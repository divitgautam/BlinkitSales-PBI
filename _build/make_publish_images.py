top, ch, gap = 11.35, 1.52, .2
for i, (big, l1, l2) in enumerate(cards):
    y = top - i * (ch + gap)
    ax.add_patch(FancyBboxPatch((.7, y - ch), W - 1.4, ch, boxstyle="round,pad=0,rounding_size=.18", fc=WHITE, ec="none", zorder=2))
    ax.add_patch(FancyBboxPatch((.7, y - ch), .12, ch, boxstyle="round,pad=0,rounding_size=.06", fc=YELLOW if i % 2 else GREEN, ec="none", zorder=3))
    ax.text(1.1, y - ch / 2, big, color=GREEN, fontsize=22 if len(big) > 8 else 27, weight="bold", va="center", zorder=4)
    ax.text(4.3, y - .5, l1, color=INK, fontsize=13, weight="bold", va="center", zorder=4)
    ax.text(4.3, y - 1.0, l2, color=MUTED, fontsize=11, va="center", zorder=4)
ax.text(.7, .62, "Fix late deliveries and assortment first; channel mix is not the lever here.", color=WHITE, fontsize=14, weight="bold", va="center")
fig.savefig(OUT / "key_insights.png", dpi=100); plt.close(fig)
print("saved images")
