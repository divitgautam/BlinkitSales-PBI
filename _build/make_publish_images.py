    ("₹1.10 Cr", "revenue from 5,000 orders, and flat", "About 255 orders a month; Apr to Oct 2024 sits 4.5% below 2023"),
    ("31%", "of orders arrive more than 5 minutes late", "69.4% on time; the late ones average 14.5 minutes over"),
