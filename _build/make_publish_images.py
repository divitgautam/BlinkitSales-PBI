    ("12.9%", "Dairy & Breakfast, the top category by line value", "The top 3 categories hold 36%; the smallest has 6.2%"),
    ("1.92x to 2.05x", "ROAS from App to Email; portfolio 1.97x", "Channels return almost the same per rupee spent"),
