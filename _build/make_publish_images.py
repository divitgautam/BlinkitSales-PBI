"""Draws docs/approach.png (1920x1080) and docs/key_insights.png (1080x1350) in the Blinkit report palette.
Run: python _build/make_publish_images.py   (numbers come from docs/reconciliation.md)."""
from pathlib import Path
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import FancyBboxPatch, FancyArrowPatch

OUT = Path(__file__).resolve().parents[1] / "docs"
NAVY, GREEN, YELLOW, GOLD, WHITE, INK, MUTED, BG = "#0A3D1F", "#0C831F", "#F8CB46", "#B98300", "#FFFFFF", "#12201A", "#4A5750", "#F4F7F2"
plt.rcParams["font.family"] = "Segoe UI"


def canvas(w, h):
    fig = plt.figure(figsize=(w, h), dpi=100)
    ax = fig.add_axes([0, 0, 1, 1]); ax.set_xlim(0, w); ax.set_ylim(0, h); ax.axis("off")
    ax.add_patch(plt.Rectangle((0, 0), w, h, fc=NAVY, ec="none", zorder=0))
    return fig, ax


# ------------------------------------------------------------------ approach diagram
W, H = 19.2, 10.8
fig, ax = canvas(W, H)
ax.text(.8, 9.95, "From raw CSVs to a checked dashboard", color=WHITE, fontsize=34, weight="bold", va="top")
ax.text(.8, 9.1, "How BlinkitSales-PBI was built: reconcile first, generate the model and report from code, check, score",
        color="#CFE6D3", fontsize=15, va="top")
stages = [
    ("01", "DATA", "Kaggle quick-commerce CSVs", ["11 files, 5,000 orders", "Mar 2023 to Nov 2024", "Customer name, email, phone", "and address dropped on load"]),
    ("02", "PYTHON", "Audit, clean, reconcile", ["Audit: order totals do not match", "item lines; ROAS column wrong", "Clean tables in data/clean", "70 headline values computed", "twice, in two ways"]),
    ("03", "MODEL", "TMDL star schema", ["Generated by a script", "10 tables, 6 relationships", "186 DAX measures", "Best Practice Analyzer 27/27", "Live checks vs Python"]),
    ("04", "REPORT", "PBIR, 7 pages", ["Built by code on a page kit", "186 visuals, alt text on all", "Drill-through, tooltips,", "phone layouts, DAX titles", "Forecast and levers page"]),
    ("05", "CHECKS", "Layout and score", ["Preflight: clipping, text fit,", "contrast, empty space", "Scorecard: 10 criteria", "6 rounds: 5.0 to 9.75 / 10"]),
]
n = len(stages); gap = .42; left = .8; cw = (W - 2 * left - (n - 1) * gap) / n; top, ch = 8.1, 5.15
for i, (num, name, tag, lines) in enumerate(stages):
    x = left + i * (cw + gap)
    ax.add_patch(FancyBboxPatch((x, top - ch), cw, ch, boxstyle="round,pad=0,rounding_size=.22", fc=WHITE, ec="none", zorder=2))
    ax.add_patch(FancyBboxPatch((x, top - .14), cw, .14, boxstyle="round,pad=0,rounding_size=.07", fc=YELLOW if i % 2 else GREEN, ec="none", zorder=3))
    ax.text(x + .32, top - .45, num, color=GREEN, fontsize=30, weight="bold", va="top", zorder=4)
    ax.text(x + .32, top - 1.32, name, color=INK, fontsize=17, weight="bold", va="top", zorder=4)
    ax.text(x + .32, top - 1.82, tag, color=MUTED, fontsize=12.5, va="top", style="italic", zorder=4)
    for j, ln in enumerate(lines):
        ax.text(x + .32, top - 2.45 - j * .5, ln, color=INK, fontsize=12.2, va="top", zorder=4)
    if i < n - 1:
        ax.add_patch(FancyArrowPatch((x + cw + .04, top - ch / 2), (x + cw + gap - .04, top - ch / 2),
                                     arrowstyle="-|>,head_length=8,head_width=6", color=YELLOW, lw=2.5, zorder=5))
bx = left + cw + gap; bw = 2 * cw + gap
ax.add_patch(FancyBboxPatch((bx, 1.6), bw, .93, boxstyle="round,pad=0,rounding_size=.18", fc=GREEN, ec="none", zorder=2))
ax.text(bx + bw / 2, 2.25, "Every card and title matches Python", color=WHITE, fontsize=14, weight="bold", ha="center", va="center", zorder=3)
ax.text(bx + bw / 2, 1.88, "₹1.10 Cr revenue  |  5,000 orders  |  69.4% on time  |  ROAS 1.97", color="#E3F4E6", fontsize=12, ha="center", va="center", zorder=3)
for cx in (bx + cw / 2, bx + cw + gap + cw / 2):
    ax.plot([cx, cx], [top - ch, 2.53], color=YELLOW, lw=2, ls=(0, (3, 3)), zorder=1)
ax.text(.8, 1.0, "The data looks synthetic and order totals do not match item lines, so the report says so on page 6.",
        color=WHITE, fontsize=14.5, va="center")
ax.text(W - .8, .45, "Power BI  |  DAX  |  TMDL + PBIR  |  Python (pandas)", color="#CFE6D3", fontsize=11.5, ha="right", va="center")
fig.savefig(OUT / "approach.png", dpi=100); plt.close(fig)

# ------------------------------------------------------------------ key insights card
W, H = 10.8, 13.5
fig, ax = canvas(W, H)
ax.text(.7, 12.85, "What 5,000 Blinkit orders say", color=WHITE, fontsize=30, weight="bold", va="top")
ax.text(.7, 12.1, "Mar 2023 to Nov 2024  |  Power BI + Python  |  synthetic-looking data, illustrative", color="#CFE6D3", fontsize=13.5, va="top")
