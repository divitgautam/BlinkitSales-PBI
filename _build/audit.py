"""Data audit for the Blinkit raw CSVs. Rerunnable and quiet: writes docs/audit.md only.
Personal fields (name, email, phone, address) are never read into the report."""
from pathlib import Path
import io
import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "docs" / "audit.md"
PII = {"customer_name", "email", "phone", "address"}

L: list[str] = []
def h(t, lvl=2): L.append(f"\n{'#' * lvl} {t}\n")
def p(t=""): L.append(t)
def n(x): return f"{x:,}"

def read(name):
    return pd.read_csv(RAW / f"{name}.csv")

T = {k: read(f"blinkit_{k}") for k in
     ["orders", "order_items", "products", "customers", "delivery_performance",
      "customer_feedback", "marketing_performance", "inventory", "inventoryNew"]}
o, oi, pr, cu = T["orders"], T["order_items"], T["products"], T["customers"]
dl, fb, mk, inv, invn = (T["delivery_performance"], T["customer_feedback"],
                         T["marketing_performance"], T["inventory"], T["inventoryNew"])

# parse dates
for df, cols in [(o, ["order_date", "promised_delivery_time", "actual_delivery_time"]),
                 (cu, ["registration_date"]), (dl, ["promised_time", "actual_time"]),
                 (fb, ["feedback_date"]), (mk, ["date"])]:
    for c in cols:
        df[c] = pd.to_datetime(df[c], errors="coerce", format="mixed" if c.endswith("time") else None)
inv["date"] = pd.to_datetime(inv["date"], format="%d-%m-%Y", errors="coerce")   # daily
invn["date"] = pd.to_datetime(invn["date"], format="%b-%y", errors="coerce")    # monthly (Mon-YY)

p("# Data audit (generated by `_build/audit.py`)")
p("Source: Kaggle `akxiit/blinkit-sales-dataset`, raw CSVs in `data/raw/` (git-ignored). "
  "Personal columns (customer_name, email, phone, address) are excluded from this report.")

# ---------- per table ----------
KEYS = {"orders": ["order_id"], "order_items": ["order_id", "product_id"], "products": ["product_id"],
        "customers": ["customer_id"], "delivery_performance": ["order_id"], "customer_feedback": ["feedback_id"],
        "marketing_performance": ["campaign_id"], "inventory": ["product_id", "date"],
        "inventoryNew": ["product_id", "date"]}
h("1. Per-table profile")
p("| table | rows | key | key unique | duplicate rows | cols with nulls (count) | date range |")
p("|---|---|---|---|---|---|---|")
for name, df in T.items():
    k = KEYS[name]
    uniq = not df.duplicated(k).any()
    dups = int(df.drop(columns=[c for c in df if c in PII]).duplicated().sum())
    nulls = {c: int(v) for c, v in df.isna().sum().items() if v}
    dts = [c for c in df if pd.api.types.is_datetime64_any_dtype(df[c])]
    rng = "; ".join(f"{c}: {df[c].min():%Y-%m-%d} to {df[c].max():%Y-%m-%d}" for c in dts[:2]) or "-"
    p(f"| {name} | {n(len(df))} | {'+'.join(k)} | {'yes' if uniq else 'NO (' + n(int(df.duplicated(k).sum())) + ' dup)'} "
      f"| {n(dups)} | {nulls or 'none'} | {rng} |")

h("Numeric ranges (min / median / max; outliers = beyond 3 IQR)")
p("| table.column | min | median | max | outliers |")
p("|---|---|---|---|---|")
for name, df in T.items():
    for c in df.select_dtypes("number").columns:
        if c.endswith("_id") or c in ("pincode", "phone"):
            continue
        s = df[c].dropna()
        q1, q3 = s.quantile([.25, .75]); i = q3 - q1
        out = int(((s < q1 - 3 * i) | (s > q3 + 3 * i)).sum()) if i > 0 else 0
        p(f"| {name}.{c} | {s.min():,.2f} | {s.median():,.2f} | {s.max():,.2f} | {out} |")

h("Categorical values (distinct counts; small sets listed)")
for name, df in T.items():
    for c in df.select_dtypes(include=["object", "string"]).columns:
        if c in PII or c.endswith("_id") or c in ("product_name", "feedback_text", "campaign_name", "reasons_if_delayed"):
            continue
        vc = df[c].value_counts(dropna=False)
        if len(vc) <= 12:
            p(f"- `{name}.{c}`: " + ", ".join(f"{k} ({n(int(v))})" for k, v in vc.items()))
        else:
            p(f"- `{name}.{c}`: {len(vc)} distinct values")
vc = dl["reasons_if_delayed"].value_counts(dropna=False)
p("- `delivery_performance.reasons_if_delayed`: " + ", ".join(f"{k} ({n(int(v))})" for k, v in vc.items()))

# ---------- key coverage ----------
h("2. Key coverage between tables (orphans both ways)")
def cov(a_name, a, b_name, b, col):
    A, B = set(a[col]), set(b[col])
    p(f"| {a_name} -> {b_name} on {col} | {n(len(A - B))} of {n(len(A))} {a_name} keys missing in {b_name} "
      f"| {n(len(B - A))} of {n(len(B))} {b_name} keys missing in {a_name} |")
p("| link | left orphans | right orphans |")
p("|---|---|---|")
cov("orders", o, "order_items", oi, "order_id")
cov("orders", o, "delivery", dl, "order_id")
cov("orders", o, "feedback", fb, "order_id")
cov("orders", o, "customers", cu, "customer_id")
cov("feedback", fb, "customers", cu, "customer_id")
cov("order_items", oi, "products", pr, "product_id")
cov("inventory", inv, "products", pr, "product_id")
cov("inventoryNew", invn, "products", pr, "product_id")
cov("orders", o, "delivery (partner)", dl, "delivery_partner_id")
fbm = fb.merge(o[["order_id", "customer_id"]], on="order_id", how="left", suffixes=("", "_o"))
p(f"\n- feedback.customer_id equals orders.customer_id for the same order: "
  f"{n(int((fbm.customer_id == fbm.customer_id_o).sum()))} of {n(len(fbm))}")
p(f"- One item per order? order_items rows {n(len(oi))}, distinct orders {n(oi.order_id.nunique())}; "
  f"max rows per order {int(oi.groupby('order_id').size().max())}; max quantity {int(oi.quantity.max())}.")
p(f"- Customers with at least one order: {n(o.customer_id.nunique())} of {n(len(cu))}; "
  f"orders per customer (orders table): max {int(o.groupby('customer_id').size().max())}, "
  f"mean {o.groupby('customer_id').size().mean():.2f}.")
p(f"- Store ids: {o.store_id.nunique()} distinct (no store dimension table exists); "
  f"delivery partners: {o.delivery_partner_id.nunique()} distinct.")

# ---------- order totals ----------
h("3. Order value checks")
