p(f"- Promised window (promised - order_date), minutes: median {((dm.promised_time - dm.order_date).dt.total_seconds() / 60).median():.1f}, "
  f"min {((dm.promised_time - dm.order_date).dt.total_seconds() / 60).min():.1f}, max {((dm.promised_time - dm.order_date).dt.total_seconds() / 60).max():.1f}.")
